"""チャート画像の読解支援（5-4）。★スコープの制限がこの機能の本体★

やること:
  文書内のチャート画像を 5-3 の仕組み（原本画像を Claude に渡す）で読み、
  「今どういう状態か」を言葉にする。複数レポートの図表を集めて要約する用途も含む。

やらないこと ─ そしてそれが仕様である理由:

  1. ★売買判断を出さない★
     日本では個別銘柄の売買判断を業として提供すると、金融商品取引法の
     投資助言・代理業の登録が必要になる可能性が高い。登録なしにその設計へ
     踏み込まないため、システムは「読解・集約の支援」に留め、判断は人間に残す。
     このモジュールは公開API(/v1)には載せない（社外へ売買判断を返す経路を作らない）。

  2. ★予測を語らない★
     LLMは「もっともらしいテクニカル分析文」を必ず生成する。書けることと
     当たることは別で、チャート形状からの将来予測はそもそも予測力が限定的。
     LLMを挟んでも予測力は上がらない。的中率を測る枠組み（app.backtest）で
     検証するまで、この機能に予測の価値があるとは主張しない。

  守り方は2段構え。プロンプト（CHART_READING_SYSTEM_PROMPT）で書かせないのが
  主で、それでも漏れたときに気づけるよう出力側にも検査（find_advice）を置く。
  生成モデルの指示追従は確率的なので、プロンプトだけを頼りにしない。
"""
from __future__ import annotations

import logging
import re

from app.llm import generate_answer

logger = logging.getLogger(__name__)


CHART_READING_SYSTEM_PROMPT = (
    "あなたはチャート画像の読解を補助するアシスタントです。"
    "与えられた画像に実際に描かれていることだけを根拠に、日本語で説明してください。"
    "\n\n書くこと（読み取れる範囲で）:"
    "\n- 対象と期間（銘柄・指数名、軸の期間、時間足）"
    "\n- 価格や値の推移（直近の方向、高値・安値、レンジの上下）"
    "\n- 図に描かれている水準（サポート/レジスタンスの線、移動平均線、出来高）"
    "\n- 形状として観察される特徴（ダブルトップ、三角保ち合い等）。"
    "ただし『そう見える』という観察として書き、意味づけはしないでください。"
    "\n\n★書いてはいけないこと（例外なし）★"
    "\n- 売買の推奨・示唆（買い/売り/保有/エントリー/利確/損切り など）"
    "\n- 将来の値動きの予想（上がる/下がる/目標株価/見通し）"
    "\n- 投資判断につながる評価（割安/割高/好機/リスクが低い など）"
    "\nこれらを求められた場合は「売買判断は行いません。判断はご自身でお願いします」"
    "と述べ、代わりに画像から読み取れる事実の説明に徹してください。"
    "\n\n画像から読み取れないことは推測せず、読み取れないと述べてください。"
    "\n\n各コンテキストには [1] [2] のような番号が付いています。"
    "説明の各文には、根拠になったコンテキストの番号を文末に [1] の形式で付けてください。"
)


# 出力側の検査に使う語。★これは証明ではなく警報★
#   プロンプトで書かせないのが主の防御で、これは「漏れたことに気づく」ための
#   仕掛け。正規表現で意味は判定できないので、取りこぼしがある前提で使う
#   （取りこぼしを減らすより、誤検知で正常な説明を壊さないことを優先している）。
# チャート読解の文脈でだけ動かすので、社内文書の「購買」等には当たらない。
ADVICE_PATTERNS: tuple[tuple[str, str], ...] = (
    (r"買[いうえ]?(?:べき|時|推奨|場|増し|下がり)", "売買推奨"),
    (r"売[りるれ]?(?:べき|時|推奨|場|抜け)", "売買推奨"),
    (r"(?:購入|売却|保有|取得|処分)(?:を)?(?:推奨|検討|おすすめ|お勧め)", "売買推奨"),
    (r"(?:エントリー|仕込[みむ]|利益確定|利確|損切[りる]|ナンピン)", "売買行動"),
    (r"目標(?:株価|価格|値)", "目標値"),
    (
        r"(?:上昇|下落|反発|反落|続伸|続落)(?:する|し)?"
        r"(?:でしょう|見込|予想|はず|と思われ)",
        "将来予想",
    ),
    (r"(?:今後|将来|来[週月年期])[^。]{0,20}(?:見通し|予想|予測|期待でき)", "将来予想"),
    (r"割[安高]", "投資評価"),
    (r"(?:好機|絶好の|狙い目|妙味)", "投資評価"),
)

_ADVICE_RE = tuple((re.compile(p), label) for p, label in ADVICE_PATTERNS)

# ★拒否・不在の文は検査から外す★
#   「目標株価は読み取れません」「売買判断は行いません」のような文は、禁止語を
#   含むが中身は正反対（まさに守れている文）。ここを落とすと、利用者に伝わるべき
#   拒否そのものが消えるうえ、「除いて表示しています」の注記が空振りして、
#   本当に漏れたときの注記まで信用されなくなる。実測で踏んだので入れてある。
#
#   否定なら何でも除く、にはしない。「買うべきではありません」は否定形だが
#   売買判断そのものなので、除外するのは★システム側の可否を述べる言い方★に限る
#   （読み取れ/行い/示され/記載され…＋ません）。
_REFUSAL_RE = re.compile(
    r"(?:読み取れ|読み取ることはでき|判断(?:は|を)?(?:行い|し)|予想(?:は|を)?(?:行い|し)"
    r"|お答えでき|回答でき|述べ|示され|記載され|描かれ|含み|算出し|提供し)"
    r"[^。]{0,6}(?:ま)?せん"
)

# 文の切れ目。日本語の句点と改行で割る（英文の "." は小数点と紛れるので使わない）
_SENTENCE_SPLIT = re.compile(r"(?<=。)|\n+")

SCOPE_NOTICE = (
    "※ この機能はチャートの読解支援です。売買判断は行いません（判断はご自身でお願いします）。"
)

REMOVED_NOTICE = (
    "※ 売買判断・将来予想に当たる記述が生成されたため、その文を除いて表示しています。"
)


def find_advice(text: str) -> list[str]:
    """売買判断・予想に当たる表現を含む文を返す（無ければ空）。

    文単位で返すのは、呼び出し側がその文だけを落とせるようにするため。
    """
    flagged: list[str] = []
    for sentence in _SENTENCE_SPLIT.split(text):
        s = sentence.strip()
        if not s:
            continue
        if _REFUSAL_RE.search(s):
            continue  # 「目標株価は読み取れません」等 = 守れている文
        if any(rx.search(s) for rx, _label in _ADVICE_RE):
            flagged.append(s)
    return flagged


def advice_labels(text: str) -> list[str]:
    """検出した種類（売買推奨・将来予想 等）。重複を除き、出現順に返す。

    判定の基準は find_advice と揃える（拒否文は数えない）。ずれると、
    落とした文が無いのに種類だけ付く といった食い違いが出る。
    """
    flagged = " ".join(find_advice(text))
    labels: list[str] = []
    for rx, label in _ADVICE_RE:
        if rx.search(flagged) and label not in labels:
            labels.append(label)
    return labels


def strip_advice(text: str) -> tuple[str, list[str]]:
    """売買判断に当たる文を落とした本文と、落とした文の一覧を返す。

    ★丸ごと捨てずに文単位で落とす★
      説明の大部分は読解として正しいことが多く、全部を捨てると利用者は
      「何も答えない機能」だと受け取ってしまう。問題のある文だけを外し、
      外したことを明示する（黙って消すと、利用者は出力を全文だと思う）。
    """
    flagged = find_advice(text)
    if not flagged:
        return text, []
    kept = [
        s.strip()
        for s in _SENTENCE_SPLIT.split(text)
        if s.strip() and s.strip() not in flagged
    ]
    return "\n".join(kept), flagged


def read_charts(question: str, contexts: list) -> dict:
    """チャート画像を読解する。{"reading", "removed", "labels"} を返す。

    contexts は 5-3 と同じ形（本文テキストと ImageContext の混在）。
    画像が1枚も無ければ読解にならないので、呼び出し側で弾くこと。

    戻り値の reading は★売買判断を含まない★。含んでいたら文ごと落とし、
    落とした文を removed に入れる（何が起きたか追えるようにする）。
    """
    raw = generate_answer(question, contexts, system=CHART_READING_SYSTEM_PROMPT)
    reading, removed = strip_advice(raw)
    if removed:
        # プロンプトの指示が効かなかったということなので、必ず記録に残す。
        # 頻発するならプロンプト側を直す手がかりになる。
        logger.warning(
            "チャート読解で売買判断に当たる記述を除きました（%d文・種類=%s）",
            len(removed),
            ",".join(advice_labels(" ".join(removed))) or "不明",
        )
        reading = f"{reading}\n\n{REMOVED_NOTICE}"
    return {
        "reading": f"{reading}\n\n{SCOPE_NOTICE}",
        "removed": removed,
        "labels": advice_labels(raw),
    }


# ---------------------------------------------------------------------------
# バックテスト用の読み取り（app.backtest から使う）
#
# ★これは予測ではない★
#   「今どちらへ向いて見えるか」という観察を1語で答えさせるだけ。
#   その観察が、その後の実際の値動きとどれくらい一致するかを測ることで、
#   「チャートの読解に情報があるのか」を数字にする。一致率が偶然と変わらなければ
#   「読解に予測力があるとは言えない」と結論できる ─ それを確かめるための道具。
# ---------------------------------------------------------------------------

TREND_STATES = ("up", "down", "flat")

TREND_SYSTEM_PROMPT = (
    "あなたはチャート画像から、直近の値動きの向きだけを観察して答える装置です。"
    "画像の右端付近の推移を見て、up（上向き）/ down（下向き）/ flat（横ばい）の"
    "いずれか1語だけを出力してください。"
    "説明・記号・前置きは一切書かないでください。"
    "\n\nこれは将来の予想ではなく、画像に描かれている傾きの観察です。"
)


def read_trend(image_context) -> str | None:
    """チャート画像から観察される直近の傾きを1語で返す。判定できなければ None。

    出力を1語に絞るのは、バックテストで機械的に突き合わせるため。
    余計な語が混ざったら None にして「読み取れなかった」として扱う
    （無理に解釈すると、当たっていないものを当たったことにしてしまう）。
    """
    raw = generate_answer("この画像の直近の傾きは？", [image_context],
                          system=TREND_SYSTEM_PROMPT)
    word = raw.strip().strip(".。").lower()
    return word if word in TREND_STATES else None
